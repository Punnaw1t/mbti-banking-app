#!/usr/bin/env python3
"""Summarise data/employees_ocean_hr.csv per department for the HR chatbot.

Usage:
    python data/build_workforce_stats.py --repo <repo root>

Output:
    lib/workforceStats.ts   counts per department (generated, do not edit)

The app only needs counts, so the 17,414 rows stay out of the browser bundle.
Every rate the chatbot reports is computed from these counts.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

PROFILE_CODES = {
    "The Mobiliser": "E", "The Steward": "C", "The Steady Hand": "S",
    "The Visionary": "O", "The Consensus Builder": "A", "The Balanced Generalist": "B",
}
TRAITS = ["O", "C", "E", "A", "N"]


def department_stats(g: pd.DataFrame) -> dict:
    rated = g[g["rating_available"] == 1]
    star = rated["nine_box"] == 3
    fit = g["executive_fit"] == "Yes"
    balanced = g["decision_profile"] == "The Balanced Generalist"
    return {
        "employees": len(g),
        "rated": len(rated),
        "kpiMet": int(g["kpis_met_more_than_80"].sum()),
        "meanTrainingScore": round(float(g["avg_training_score"].mean()), 1),
        "meanPercentile": {t: round(float(g[f"{t}_pct"].mean()), 1) for t in TRAITS},
        "profiles": {c: int((g["decision_profile"] == name).sum()) for name, c in PROFILE_CODES.items()},
        "executiveFit": int(fit.sum()),
        "performanceBand": {b: int((rated["performance_band"] == b).sum()) for b in ["Low", "Medium", "High"]},
        "potentialBand": {b: int((g["potential_band"] == b).sum()) for b in ["Low", "Medium", "High"]},
        "nineBox": {str(i): int((rated["nine_box"] == i).sum()) for i in range(1, 10)},
        # Combined rules X1 to X3 from the report (section 3.4 and Part 2).
        "x1StarExecutiveFit": int((star & fit[rated.index]).sum()),
        "x2FitLowPerformance": int((fit[rated.index] & (rated["performance_band"] == "Low")).sum()),
        "x3HighPotentialBalanced": int((rated["nine_box"].isin([2, 3]) & balanced[rated.index]).sum()),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, required=True)
    repo = ap.parse_args().repo
    df = pd.read_csv(repo / "data/employees_ocean_hr.csv")
    stats = {dept: department_stats(g) for dept, g in df.groupby("department")}
    body = json.dumps(stats, indent=2)
    (repo / "lib/workforceStats.ts").write_text(
        "// Generated by data/build_workforce_stats.py from data/employees_ocean_hr.csv. Do not edit.\n"
        "// Counts per department; the OCEAN columns of that file are a synthetic link (see data/README.md).\n\n"
        "export interface DepartmentStats {\n"
        "  employees: number;\n  rated: number;\n  kpiMet: number;\n  meanTrainingScore: number;\n"
        "  meanPercentile: Record<\"O\" | \"C\" | \"E\" | \"A\" | \"N\", number>;\n"
        "  profiles: Record<\"E\" | \"C\" | \"S\" | \"O\" | \"A\" | \"B\", number>;\n"
        "  executiveFit: number;\n"
        "  performanceBand: Record<\"Low\" | \"Medium\" | \"High\", number>;\n"
        "  potentialBand: Record<\"Low\" | \"Medium\" | \"High\", number>;\n"
        "  nineBox: Record<string, number>;\n"
        "  x1StarExecutiveFit: number;\n  x2FitLowPerformance: number;\n  x3HighPotentialBalanced: number;\n"
        "}\n\n"
        f"export const WORKFORCE_STATS: Record<string, DepartmentStats> = {body};\n"
    )
    print(f"wrote lib/workforceStats.ts, {len(df)} employees in {len(stats)} departments")


if __name__ == "__main__":
    main()
